import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); from common import ROOT, OUT
import subprocess, time, sys
from playwright.sync_api import sync_playwright
srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8777', '--directory', ROOT], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1); errs=[]; M=60000
def burn(page): return page.locator('.card:has-text("Fuel burn")').inner_text().replace('\n',' | ')[:160]
def click(page, sel): page.locator(sel).first.dispatch_event('click'); page.wait_for_timeout(200)
try:
    with sync_playwright() as p:
        b = p.chromium.launch(); page = b.new_page(viewport={'width': 412, 'height': 1400})
        page.on('pageerror', lambda e: errs.append(str(e)))
        page.clock.install(time=time.mktime((2026, 10, 25, 9, 0, 0, 0, 0, -1)))
        page.goto('http://localhost:8777/')
        page.fill('#nt-tail', 'N12345'); page.click('text=Add aircraft')
        page.fill('#s-ete', '2:00'); page.locator('#s-ete').dispatch_event('input'); page.fill('#s-fuel', '40'); page.locator('#s-fuel').dispatch_event('input')
        page.wait_for_timeout(300)
        print('setup calc:', page.inner_text('#setupCalc').replace('\n',' | '))
        page.click('text=Build plan'); page.wait_for_timeout(300)
        print('plan legend:', page.locator('.legend').first.inner_text().replace('\n',' '))
        print('last leg phases:', page.locator('.legrow').last.inner_text().replace('\n',' | ')[:200])
        page.click('text=Start flight'); page.locator('#sd-at').fill('0:00:00'); page.locator('#sd-at').dispatch_event('input'); click(page, '[data-act=saveStart]')
        page.goto('http://localhost:8777/#fly'); page.wait_for_timeout(300)
        page.clock.run_for(60*M); page.wait_for_timeout(300)
        print('cruise card:', burn(page))
        click(page, '[data-sheet=descent]'); page.fill('#sd-dgph', '9'); click(page, '[data-act=saveDescent]')
        page.clock.run_for(5*M); page.wait_for_timeout(1200)
        print('descent card:', burn(page))
        page.screenshot(path=OUT+'/descent_fly.png', full_page=True)
        click(page, '.card:has-text("Fuel burn") [data-sheet=level]'); click(page, '[data-act=saveLevel]')
        page.clock.run_for(10*M); page.wait_for_timeout(1200)
        print('level card:', burn(page))
        click(page, '[data-sheet=descent]'); print('step sheet:', page.locator('#sheet h2').inner_text(), page.locator('#sd-dgph').input_value()); page.fill('#sd-dgph', '8'); click(page, '[data-act=saveDescent]')
        page.clock.run_for(10*M); page.wait_for_timeout(1200)
        click(page, '[data-sheet=landed]'); click(page, '[data-act=saveLanded]')
        page.clock.run_for(3*M); page.wait_for_timeout(1200)
        print('taxi-in card:', burn(page))
        print('dest card gone:', page.locator('text=To KVBT').count() == 0)
        st = page.evaluate("(() => { const s = JSON.parse(localStorage['burnplan.v1']); const f = Object.values(s.flights)[0]; return f.events.map(e => e.type + (e.gph ? '@'+e.gph : '')); })()")
        print('events:', st)
        page.goto('http://localhost:8777/#plan'); page.wait_for_timeout(300)
        print('plan rows:', [t.split('\n')[0] for t in page.locator('.legrow').all_inner_texts()][-3:])
        page.goto('http://localhost:8777/#log'); page.wait_for_timeout(200); page.locator('.item').first.dispatch_event('click'); page.wait_for_timeout(300)
        print('log:', [t.split('\n')[0] for t in page.locator('.evrow.tap').all_inner_texts()])
        b.close()
finally: srv.terminate()
print('ERRORS', errs)
