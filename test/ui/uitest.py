        shot('04-start-sheet')
        page.click('[data-act=sdSofar][data-v=manual]')
        page.wait_for_timeout(100)
        print('seeded rows:', [page.locator(f'[data-row="{i}.at"]').input_value() for i in range(page.locator('[data-row$=".at"]').count())])
