        print('start preview (manual):', page.inner_text('#sheetPreview').replace('\n', ' | '))
        shot('04b-start-manual')
        page.click('[data-act=saveStart]')
        page.wait_for_timeout(200)
        shot('05-fly-start')
        print('fly after start:', page.inner_text('#flyLive').replace('\n', ' | ')[:330])
